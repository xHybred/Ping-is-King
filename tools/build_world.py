"""Convert Natural Earth 110m land polygons to an SVG path for the map.

    python tools/build_world.py data/raw/ne_110m_land.geojson cod_region_filter/ui/world.js

The output uses full-world Mercator coordinates in a 1000 x 500 box, which is
what ui/app.js transforms for zoom and pan.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

W = 1000.0
H = 500.0


def mercator_y(lat: float) -> float:
    lat = max(-85.0, min(85.0, lat))
    rad = math.radians(lat)
    return (1 - math.log(math.tan(rad) + 1 / math.cos(rad)) / math.pi) / 2 * H


def ring_path(ring: list[list[float]]) -> str:
    points: list[tuple[float, float]] = []
    for lon, lat, *_ in ring:
        x = round((lon + 180.0) / 360.0 * W, 1)
        y = round(mercator_y(lat), 1)
        if not points or abs(points[-1][0] - x) + abs(points[-1][1] - y) >= 0.8:
            points.append((x, y))
    if len(points) < 3:
        return ""
    return "M" + "L".join(f"{x},{y}" for x, y in points) + "Z"


def main(source: Path, target: Path) -> int:
    data = json.loads(source.read_text(encoding="utf-8"))
    parts: list[str] = []
    for feature in data.get("features", []):
        geometry = feature.get("geometry") or {}
        kind = geometry.get("type")
        coords = geometry.get("coordinates") or []
        polygons = [coords] if kind == "Polygon" else coords if kind == "MultiPolygon" else []
        for polygon in polygons:
            for ring in polygon:
                path = ring_path(ring)
                if path:
                    parts.append(path)
    joined = "".join(parts)
    target.write_text(
        "// Generated by tools/build_world.py from Natural Earth 1:110m land. Public domain.\n"
        f"const WORLD_LAND_PATH = {json.dumps(joined)};\n",
        encoding="utf-8",
    )
    print(f"{len(parts)} rings, {len(joined)} bytes -> {target}")
    return 0


if __name__ == "__main__":
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "data/raw/ne_110m_land.geojson")
    dst = Path(sys.argv[2] if len(sys.argv) > 2 else "cod_region_filter/ui/world.js")
    raise SystemExit(main(src, dst))
